import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";
import glob from "fast-glob";

const artifactRoot = path.dirname(fileURLToPath(import.meta.url));
const workspaceRoot = path.resolve(artifactRoot, "../..");
const mockupsDir = "src/components/mockups";
const outputPath = path.join(artifactRoot, "src/.generated/mockup-components.ts");
const writerPath = path.join(
  workspaceRoot,
  "scripts/failure_gate/run_writer.py",
);
const workerFlag = "--failure-gate-writer-worker";

function inheritedLockFd() {
  const value = process.env.FAILURE_GATE_WRITER_FD;
  if (value === undefined) return null;
  const fd = Number(value);
  if (!Number.isSafeInteger(fd) || fd < 3) {
    throw new Error("invalid inherited Failure Gate writer descriptor");
  }
  return fd;
}

function runWithWriterLock(argv) {
  const fd = inheritedLockFd();
  const writerArgs = [writerPath];
  if (fd !== null) writerArgs.push("--inherited-lock-fd", String(fd));
  writerArgs.push("--", ...argv);
  const result = spawnSync("python3", writerArgs, {
    cwd: workspaceRoot,
    stdio:
      fd === null
        ? "inherit"
        : ["inherit", "inherit", "inherit", fd],
  });

  if (result.error) throw result.error;
  if (result.signal) throw new Error(`mockup generator stopped by ${result.signal}`);
  if (result.status !== 0) {
    throw new Error(`mockup generator failed with exit ${result.status}`);
  }
}

if (process.argv[2] !== workerFlag) {
  runWithWriterLock([
    process.execPath,
    fileURLToPath(import.meta.url),
    workerFlag,
  ]);
} else {
  // A direct worker-mode invocation is still required to prove or acquire the
  // actual lock descriptor before reading inputs or writing generated output.
  const fd = inheritedLockFd();
  if (fd === null) {
    throw new Error("mockup generator worker requires the writer lock");
  }
  const verified = spawnSync(
    "python3",
    [writerPath, "--inherited-lock-fd", String(fd), "--verify-lock-fd"],
    {
      cwd: workspaceRoot,
      stdio: ["ignore", "inherit", "inherit", fd],
    },
  );
  if (verified.error) throw verified.error;
  if (verified.signal) {
    throw new Error(`mockup writer verification stopped by ${verified.signal}`);
  }
  if (verified.status !== 0) {
    throw new Error(`mockup writer verification failed with exit ${verified.status}`);
  }

  const files = await glob(`${mockupsDir}/**/*.tsx`, {
    cwd: artifactRoot,
    ignore: ["**/_*/**", "**/_*.tsx"],
  });

  const entries = files
    .map((file) => ({
      globKey: "./" + file.slice("src/".length),
      importPath: path.posix.relative("src/.generated", file),
    }))
    .map(
      ({ globKey, importPath }) =>
        `  ${JSON.stringify(globKey)}: () => import(${JSON.stringify(importPath)})`,
    )
    .join(",\n");

  const source = [
    "// This file is auto-generated by mockupPreviewPlugin.ts.",
    "type ModuleMap = Record<string, () => Promise<Record<string, unknown>>>;",
    "export const modules: ModuleMap = {",
    entries,
    "};",
    "",
  ].join("\n");

  let currentSource = null;
  try {
    currentSource = readFileSync(outputPath, "utf8");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }

  if (source !== currentSource) {
    mkdirSync(path.dirname(outputPath), { recursive: true });
    writeFileSync(outputPath, source);
  }
}
